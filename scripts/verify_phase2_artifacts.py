"""Validate current evidence and render the proposal-only human trace matrix."""
import json
from pathlib import Path

from aps.core import validate as phase1_validate
from aps_governance.contracts import sha, validate
from aps_governance.gateway import verify_receipts
from aps_governance.signing import read_public
from aps_governance.traceability import propose

root = Path(__file__).resolve().parents[1]
p = root / 'artifacts/phase2'
report = json.loads((root / 'artifacts/report.json').read_text())
phase1_validate('report', report)
assert len(report['hazards']) == 96 and not report['requirements']
assert all(h['review_state'] == 'unverified' for h in report['hazards'])
trace = validate('traceability', json.loads((p / 'traceability.json').read_text()))
assert trace == propose(report), 'Trace must match current report proposals'
assert len(trace['requirements']) == 16
assert all(r['state'] == 'proposed' and r['review_signature'] is None for r in trace['requirements'])
simulation = validate('policy-simulation', json.loads((p / 'policy-simulation.json').read_text()))
assert simulation['passed'] and all(r['passed'] for r in simulation['results'])
verify_receipts(json.loads((p / 'authorization-receipts.json').read_text()),
                read_public((p / 'receipt-public-key.txt').read_text().strip()))
for name in ('enforcement-latency', 'integration-latency'):
    validate(name, json.loads((p / (name + '.json')).read_text()))

hazards = {h['id']: h for h in report['hazards']}
def cell(value):
    return str(value).replace('|', '\\|').replace('\n', ' ')

lines = ['# Phase 2 hazard-to-control traceability matrix', '',
    'Generated by `scripts/verify_phase2_artifacts.py` from the current report and trace JSON.', '',
    f'Report digest: `{sha(report)}`. Trace digest: `{sha(trace)}`.', '',
    'All 96 findings remain unverified. These 16 curated reference rows are proposed requirements; '
    'there are zero approved requirements and no real human approvals. The remaining 80 generated '
    'findings have no individual trace proposal. Implemented means a source/test link exists; '
    'human review has not established effectiveness or complete hazard coverage.', '',
    '| Hazard / reference / deviation | Proposed requirement (version 1) | Control / status | Source / test evidence | Coverage limit or gap |',
    '| --- | --- | --- | --- | --- |']
for r in trace['requirements']:
    h = hazards[r['hazard_id']]
    for c in r['controls']:
        values = [f"{h['id']} / {h['provenance']['scenario_id']} / {h['deviation']}",
                  f"{r['id']} — {r['text']} (proposed)",
                  f"{c['id']} — {c['description']} ({c['status']})",
                  f"{c['implementation']} / {c['test']}", c['gap']]
        lines.append('| ' + ' | '.join(map(cell, values)) + ' |')
lines += ['', 'Control sources resolve under `packages/governance/aps_governance/`, '
          '`policies/v1/`, or repository-root `schemas/`. Named tests are in '
          '`tests/test_governance.py`; `none` identifies an explicit gap.', '',
          'Promotion requires actual Phase 1 human review and independent signed Phase 2 approval. '
          'The disposable demo bootstraps only a sandbox baseline. Receipts record authorization '
          'decisions and are not safety proof. Local OS/keys are trusted; TLS/remote deployment '
          'and external ledger anchoring are absent. See `THREAT_MODEL.md`.', '']
(root / 'docs/TRACEABILITY_MATRIX.md').write_text('\n'.join(lines))
print('Validated current report, exact proposals, policy simulation, public-key receipt chain, and latency schemas; rendered 16 proposed trace rows.')
